// Build script for @aakashiic/tokens
// Reads tokens/**/*.json (DTCG format) and writes:
//   dist/css/tokens.css         shared values in :root + one [data-app="..."] block per app   (DS-1.2, DS-1.5)
//   dist/tailwind/theme.css     Tailwind v4 @theme block that points at the CSS variables    (DS-1.3)
//   dist/scss/_tokens.scss      SCSS variables for Angular that point at the CSS variables   (DS-1.4)

import StyleDictionary from 'style-dictionary';
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';

const PREFIX = 'ds'; // every CSS variable starts with --ds- so it never clashes with Tailwind/shadcn/Bootstrap names
const DEFAULT_THEME = 'datavault'; // the reference look; used when <html> has no data-app attribute

// tokens/themes/<app>.json is the light theme; <app>-dark.json is that app's optional dark theme.
// Order: default first (its block also matches :root, and later blocks of equal specificity override it),
// then other light themes, then dark themes (higher specificity, so order is only for readability).
const THEMES = readdirSync('tokens/themes')
  .filter((f) => f.endsWith('.json'))
  .map((f) => {
    const file = f.replace('.json', '');
    const dark = file.endsWith('-dark');
    return { file, app: dark ? file.slice(0, -'-dark'.length) : file, dark };
  })
  .sort((a, b) => a.dark - b.dark || (a.app === DEFAULT_THEME ? -1 : b.app === DEFAULT_THEME ? 1 : a.app.localeCompare(b.app)));
if (!THEMES.some((t) => t.file === DEFAULT_THEME)) throw new Error(`Default theme "${DEFAULT_THEME}" not found in tokens/themes/`);
for (const t of THEMES.filter((t) => t.dark)) {
  if (!THEMES.some((l) => !l.dark && l.app === t.app)) throw new Error(`${t.file}.json has no matching light theme ${t.app}.json`);
}

// Dark mode: the class shadcn/next-themes already put on <html>, or an explicit data-theme attribute.
const themeSelector = ({ app, dark }) => {
  if (dark) return `[data-app="${app}"].dark, [data-app="${app}"][data-theme="dark"]`;
  return app === DEFAULT_THEME ? `:root, [data-app="${app}"]` : `[data-app="${app}"]`;
};

// Every theme must define exactly the same token names, or a component would render with a missing colour in one app.
const flatNames = (obj, prefix = []) =>
  Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object' && '$value' in v ? [[...prefix, k].join('.')] : flatNames(v, [...prefix, k]),
  );
const namesOf = (file) => flatNames(JSON.parse(readFileSync(`tokens/themes/${file}.json`, 'utf8'))).sort();
const referenceNames = namesOf(DEFAULT_THEME);
for (const { file } of THEMES) {
  const names = namesOf(file);
  const missing = referenceNames.filter((n) => !names.includes(n));
  const extra = names.filter((n) => !referenceNames.includes(n));
  if (missing.length || extra.length) {
    throw new Error(`Theme "${file}" does not match "${DEFAULT_THEME}". Missing: [${missing}] Extra: [${extra}]`);
  }
}

// Transforms: like the built-in "css" group, but WITHOUT size/rem, so px values stay px
// (VRetail scales <html> to 95%, which is why its tokens use px).
const transforms = ['attribute/cti', 'name/kebab', 'color/css', 'fontFamily/css', 'shadow/css/shorthand', 'cubicBezier/css'];

const isTheme = (token) => token.filePath.includes('tokens/themes/');
const isShared = (token) => !isTheme(token);

// ---------- Custom formats ----------

// Tailwind v4 @theme. "inline" makes utilities use var(--ds-...) directly, so the theme can switch at runtime.
StyleDictionary.registerFormat({
  name: 'tailwind/theme',
  format: ({ dictionary }) => {
    const lines = dictionary.allTokens.map((t) => {
      const [group, ...rest] = t.path;
      const key = rest.join('-');
      let twName;
      if (group === 'color') twName = `--color-${key}`;
      else if (group === 'font' && rest[0] === 'family') twName = `--font-${rest.slice(1).join('-')}`;
      else if (group === 'font' && rest[0] === 'size') twName = `--text-${rest.slice(1).join('-')}`;
      else if (group === 'font' && rest[0] === 'weight') twName = `--font-weight-${rest.slice(1).join('-')}`;
      else if (group === 'radius') twName = `--radius-${key}`;
      else if (group === 'shadow') twName = `--shadow-${key}`;
      else if (group === 'spacing') twName = `--spacing-${key}`;
      else if (group === 'control') twName = `--spacing-control-${rest.slice(1).join('-')}`; // gives h-control-md etc.
      else if (group === 'motion' && rest[0] === 'ease') twName = `--ease-${rest.slice(1).join('-')}`; // ease-standard
      else return null; // motion.duration has no Tailwind theme namespace; use duration-(--ds-motion-duration-fast)
      return `  ${twName}: var(--${t.name});`;
    });
    return `/* Generated by @aakashiic/tokens. Do not edit by hand. */\n@theme inline {\n${lines.filter(Boolean).join('\n')}\n}\n`;
  },
});

// SCSS for Angular: variables point at the CSS variables, so data-app theme switching works in VRetail too.
StyleDictionary.registerFormat({
  name: 'scss/css-var-refs',
  format: ({ dictionary }) =>
    `// Generated by @aakashiic/tokens. Do not edit by hand.\n// Load dist/css/tokens.css globally for these to resolve.\n` +
    dictionary.allTokens.map((t) => `$${t.name}: var(--${t.name});`).join('\n') +
    '\n',
});

// ---------- Builds ----------

rmSync('dist', { recursive: true, force: true });

// 1) Shared values -> :root
await new StyleDictionary({
  source: ['tokens/shared/**/*.json'],
  usesDtcg: true,
  log: { verbosity: 'default' },
  platforms: {
    css: {
      transforms,
      prefix: PREFIX,
      buildPath: 'dist/tmp/',
      files: [{ destination: 'shared.css', format: 'css/variables', options: { selector: ':root', outputReferences: true } }],
    },
  },
}).buildAllPlatforms();

// 2) One colour block per app (and per dark theme) -> [data-app="..."]
for (const theme of THEMES) {
  await new StyleDictionary({
    source: ['tokens/shared/**/*.json', `tokens/themes/${theme.file}.json`],
    usesDtcg: true,
    platforms: {
      css: {
        transforms,
        prefix: PREFIX,
        buildPath: 'dist/tmp/',
        files: [{ destination: `theme-${theme.file}.css`, format: 'css/variables', filter: isTheme, options: { selector: themeSelector(theme) } }],
      },
    },
  }).buildAllPlatforms();
}

// 3) Tailwind + SCSS outputs (names are the same for every theme, so build them from any one theme)
await new StyleDictionary({
  source: ['tokens/shared/**/*.json', `tokens/themes/${DEFAULT_THEME}.json`],
  usesDtcg: true,
  platforms: {
    tailwind: { transforms, prefix: PREFIX, buildPath: 'dist/tailwind/', files: [{ destination: 'theme.css', format: 'tailwind/theme' }] },
    scss: { transforms, prefix: PREFIX, buildPath: 'dist/scss/', files: [{ destination: '_tokens.scss', format: 'scss/css-var-refs' }] },
  },
}).buildAllPlatforms();

// 4) Combine shared + themes into one file the apps import
mkdirSync('dist/css', { recursive: true });
const parts = ['shared', ...THEMES.map((t) => `theme-${t.file}`)].map((f) => readFileSync(`dist/tmp/${f}.css`, 'utf8'));
writeFileSync('dist/css/tokens.css', parts.join('\n'));
rmSync('dist/tmp', { recursive: true, force: true });

console.log(`\n✔ Built tokens for themes: ${THEMES.map((t) => t.file).join(', ')}`);
